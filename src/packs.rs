use crate::hardware::MemoryBudget;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CapabilityPack {
    /// Local OpenAI-compatible AI gateway (Whisper + Embeddings + 8B LLM with 5m idle unload).
    LocalAiGateway,
    /// Residential browser worker (Playwright persistent context) + OpenClaw / n8n workflow engine.
    AgentAndBrowser,
    /// Self-hosted GitHub Actions ARM64 / x86_64 runner.
    GithubCiRunner,
    /// Mobile Telegram / Slack bridge with tool-approval buttons and kill switch.
    PhoneCommandBridge,
}

impl CapabilityPack {
    #[must_use = "returns the full catalog of appliance capability packs"]
    pub fn all() -> &'static [CapabilityPack] {
        &[
            CapabilityPack::LocalAiGateway,
            CapabilityPack::AgentAndBrowser,
            CapabilityPack::GithubCiRunner,
            CapabilityPack::PhoneCommandBridge,
        ]
    }

    #[must_use = "returns the human-readable title of the capability pack"]
    pub fn display_name(self) -> &'static str {
        match self {
            CapabilityPack::LocalAiGateway => {
                "Local AI Microservices (Whisper + Embeddings + On-Demand 8B LLM)"
            }
            CapabilityPack::AgentAndBrowser => {
                "24/7 Agent & Residential Browser Host (OpenClaw + n8n + Playwright)"
            }
            CapabilityPack::GithubCiRunner => "Self-Hosted GitHub Actions Runner (Native Speed)",
            CapabilityPack::PhoneCommandBridge => {
                "Phone Command Center (Telegram/Slack Approvals & Kill Switch)"
            }
        }
    }
}

/// Generates an OrbStack / Docker Compose manifest tailored to the selected capability packs
/// and the hardware's calculated memory budget.
#[must_use = "compose YAML should be written to disk or inspected"]
pub fn render_compose_stack(packs: &[CapabilityPack], budget: &MemoryBudget) -> String {
    let mut out =
        String::from("# Generated by cheap-otto — Headless AI & Dev Appliance Stack\nservices:\n");

    if packs.contains(&CapabilityPack::AgentAndBrowser) {
        out.push_str(&format!(
            "  n8n-orchestrator:\n\
             \x20   image: docker.n8n.io/n8nio/n8n:1.82.0\n\
             \x20   restart: unless-stopped\n\
             \x20   ports:\n\
             \x20     - \"127.0.0.1:5678:5678\"\n\
             \x20   environment:\n\
             \x20     - N8N_SECURE_COOKIE=false\n\
             \x20     - GENERIC_TIMEZONE=UTC\n\
             \x20   volumes:\n\
             \x20     - ./data/n8n:/home/node/.n8n\n\
             \x20   deploy:\n\
             \x20     resources:\n\
             \x20       limits:\n\
             \x20         memory: {}M\n\n\
             \x20 residential-browser:\n\
             \x20   image: mcr.microsoft.com/playwright:v1.51.0-noble\n\
             \x20   restart: unless-stopped\n\
             \x20   ipc: host\n\
             \x20   command: [\"npx\", \"playwright\", \"run-server\", \"--port\", \"3003\", \"--host\", \"0.0.0.0\"]\n\
             \x20   ports:\n\
             \x20     - \"127.0.0.1:3003:3003\"\n\
             \x20   volumes:\n\
             \x20     - ./data/browser-profile:/home/pwuser/profile\n\n",
            budget.agent_and_browser_mb
        ));
    }

    if packs.contains(&CapabilityPack::LocalAiGateway) {
        out.push_str(&format!(
            "  local-ai-gateway:\n\
             \x20   image: ollama/ollama:0.5.12\n\
             \x20   restart: unless-stopped\n\
             \x20   ports:\n\
             \x20     - \"127.0.0.1:11434:11434\"\n\
             \x20   environment:\n\
             \x20     - OLLAMA_KEEP_ALIVE={}s\n\
             \x20     - OLLAMA_MAX_LOADED_MODELS=1\n\
             \x20   volumes:\n\
             \x20     - ./data/models:/root/.ollama\n\
             \x20   deploy:\n\
             \x20     resources:\n\
             \x20       limits:\n\
             \x20         memory: {}M\n\n\
             \x20 local-whisper:\n\
             \x20   image: onerahmet/openai-whisper-asr-webservice:v1.7.1\n\
             \x20   restart: unless-stopped\n\
             \x20   ports:\n\
             \x20     - \"127.0.0.1:8089:9000\"\n\
             \x20   environment:\n\
             \x20     - ASR_MODEL=base\n\
             \x20     - ASR_ENGINE=openai_whisper\n\
             \x20   volumes:\n\
             \x20     - ./data/voice-inbox:/inbox\n\
             \x20     - ./data/transcripts:/out\n\n",
            budget.llm_idle_unload_secs,
            budget.local_ai_max_mb.max(1024)
        ));
    }

    if packs.contains(&CapabilityPack::GithubCiRunner) {
        out.push_str(&format!(
            "  github-ci-runner:\n\
             \x20   image: myoung34/github-runner:2.322.0-ubuntu-noble\n\
             \x20   restart: unless-stopped\n\
             \x20   environment:\n\
             \x20     - RUNNER_NAME=cheap-otto-m1-runner\n\
             \x20     - RUNNER_WORKDIR=/tmp/runner/work\n\
             \x20     - LABELS=self-hosted,ARM64,cheap-otto\n\
             \x20   volumes:\n\
             \x20     - ./data/github-runner:/tmp/runner\n\
             \x20   deploy:\n\
             \x20     resources:\n\
             \x20       limits:\n\
             \x20         memory: {}M\n\n",
            budget.ci_runner_mb
        ));
    }

    if packs.contains(&CapabilityPack::PhoneCommandBridge) {
        out.push_str(
            "  uptime-monitor:\n\
             \x20   image: louislam/uptime-kuma:1.23.16\n\
             \x20   restart: unless-stopped\n\
             \x20   ports:\n\
             \x20     - \"127.0.0.1:3001:3001\"\n\
             \x20   volumes:\n\
             \x20     - ./data/uptime-kuma:/app/data\n",
        );
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::hardware::{CpuArch, HardwareError, HardwareProfile};

    #[test]
    fn renders_compose_stack_with_idle_unload_whisper_and_ci_runner() -> Result<(), HardwareError> {
        let profile = HardwareProfile {
            model_name: "MacBookAir10,1".to_string(),
            arch: CpuArch::AppleSilicon,
            memory_gb: 16,
            has_battery: true,
            battery_health_percent: Some(90),
            fanless: true,
        };
        let budget = profile.compute_memory_budget()?;
        let yaml = render_compose_stack(CapabilityPack::all(), &budget);

        assert!(yaml.contains("n8n-orchestrator:"));
        assert!(yaml.contains("residential-browser:"));
        assert!(yaml.contains("local-whisper:"));
        assert!(yaml.contains("127.0.0.1:8089:9000"));
        assert!(yaml.contains("github-ci-runner:"));
        assert!(yaml.contains("OLLAMA_KEEP_ALIVE=300s"));
        assert!(yaml.contains("memory: 6144M"));
        Ok(())
    }
}
